def _resolve_version() -> str:
    """Return the package version.

    The version is derived from the repository tags by setuptools_scm, which
    writes it twice at build/install time: into the generated
    ``gridstate/_version.py`` and into the package metadata. In an editable
    install the metadata is refreshed only by a reinstall and can lag behind the
    working tree, while ``_version.py`` is regenerated by every build of that
    tree, so it is preferred. The metadata is the fallback (for example a wheel
    built without the generated module); a bare source tree that was never
    installed or built reports ``0+unknown``.
    """
    try:
        return str(import_module("gridstate._version").__version__)
    except (ImportError, AttributeError):
        pass
    try:
        return version("gridstate")
    except PackageNotFoundError:
        return "0+unknown"



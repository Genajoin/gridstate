"""SE on the standard IEEE models (case14 / case30 / case118): pandapower fixtures.

A regression on the standard public test networks. The fixtures
(``tests/test_data/ieee/caseNN.npz``) are built by ``tools/gen_ieee_fixtures.py``
(pandapower → PF → a synthetic observed z-vector with Gaussian noise, fixed seed).
**This test does NOT import pandapower**: it reads only the contract npz through
:func:`gridstate.load_se_input_npz` plus the PF truth sidecar (``np.load``), runs
WLS SE and compares |V| and angles with the power flow solution.

Angles are compared **relative to the slack node**: a global phase rotation is unobservable
without an absolute angle anchor, and pandapower sets a slack angle != 0 in different cases
(case118: 30 deg). Tolerances achieved on the current fixtures (max over nodes, with noise
sigma_V=0.5% Vn, sigma_P/Q=2 MW): |dV| <= 0.006 p.u., |dtheta| <= 0.7 deg; the thresholds below are taken
with a margin.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from gridstate.contract import run as run_se
from gridstate.contract.serialize import load_se_input_npz
from gridstate.pipeline import PipelineConfig


_DATA_DIR = Path(__file__).parent / "test_data" / "ieee"

# Tolerances (with a margin over the achieved ~0.006 p.u. / ~0.7 deg).
_TOL_V_PU = 0.015
_TOL_DELTA_DEG = 2.0

_CASES = ["case14", "case30", "case118"]


def _solve_and_compare(case: str) -> tuple[bool, int, float, float]:
    """Run WLS SE on a fixture and return (success, iters, max|dV|pu, max|dtheta|deg)."""
    se_in = load_se_input_npz(_DATA_DIR / f"{case}.npz")
    truth = np.load(_DATA_DIR / f"{case}_truth.npz")

    out = run_se(se_in, config=PipelineConfig(algorithm="wls"), validate=False)

    # Node Vnom from the input model (to convert kV -> p.u.).
    nodes = se_in.model.nodes.to_numpy()
    vn_of = {int(r["id"]): float(r["voltage_nominal"]) for r in nodes}

    truth_of = {
        int(truth["node_id"][i]): (
            float(truth["vm_pu_true"][i]),
            float(truth["va_degree_true"][i]),
        )
        for i in range(len(truth["node_id"]))
    }
    slack_id = int(truth["slack_id"])

    ids = [int(x) for x in out.nodes["id"]]
    vm_kv = out.nodes["voltage_magnitude"]
    va_deg = np.degrees(out.nodes["voltage_angle"])

    slack_pos = ids.index(slack_id)
    va_ref = va_deg - va_deg[slack_pos]
    va_true_slack = truth_of[slack_id][1]

    max_dv = 0.0
    max_dd = 0.0
    for k, bid in enumerate(ids):
        vm_true, va_true = truth_of[bid]
        max_dv = max(max_dv, abs(vm_kv[k] / vn_of[bid] - vm_true))
        max_dd = max(max_dd, abs(va_ref[k] - (va_true - va_true_slack)))

    return bool(out.success), int(out.iterations), max_dv, max_dd


@pytest.mark.parametrize("case", _CASES)
def test_ieee_case_fixture_exists(case: str) -> None:
    """Fixtures are present (generated by tools/gen_ieee_fixtures.py)."""
    assert (_DATA_DIR / f"{case}.npz").exists(), f"no fixture {case}.npz"
    assert (_DATA_DIR / f"{case}_truth.npz").exists(), f"no truth {case}_truth.npz"


@pytest.mark.parametrize("case", _CASES)
def test_ieee_case_se_matches_powerflow(case: str) -> None:
    """WLS SE converges and reproduces the PF solution within tolerance."""
    success, iters, max_dv, max_dd = _solve_and_compare(case)

    assert success, f"{case}: WLS did not converge ({iters} iterations)"
    assert max_dv <= _TOL_V_PU, f"{case}: max|dV|={max_dv:.4f} p.u. > {_TOL_V_PU}"
    assert max_dd <= _TOL_DELTA_DEG, f"{case}: max|dδ|={max_dd:.4f}° > {_TOL_DELTA_DEG}"


def test_ieee_cases_are_nontrivial() -> None:
    """Sanity: the fixtures really carry different networks with measurements."""
    sizes = {}
    for case in _CASES:
        se_in = load_se_input_npz(_DATA_DIR / f"{case}.npz")
        n_nodes = len(se_in.model.nodes)
        n_meas = len(se_in.model.measurements)
        assert n_nodes > 0 and n_meas > n_nodes, (
            f"{case}: too few measurements ({n_meas}/{n_nodes})"
        )
        sizes[case] = n_nodes
    # models of different size
    assert sizes["case14"] < sizes["case30"] < sizes["case118"]
